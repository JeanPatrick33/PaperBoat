#!/usr/bin/env python3
"""Add the DE/FR/ES pause-menu label images of the PAL ROM (the per-language pause_gfx overlays):
 - appends entries to assets/yaml/pal/misc/pause.yml
 - appends the paths to include/assets/misc/pause.h
 - writes src/pause/pause_gfx_pal_labels.inc.c (per-language display lists + lookup table)
usage: gen_pause_langs.py <repo>"""
import sys
repo=sys.argv[1]
START={'de':0x169350,'fr':0x16B3D0,'es':0x16D450}
# name, w, h, log2w (tile), C suffix, label index
ITEMS=[('banner_hp',64,16,6,'Hp','PAUSE_LBL_HP'),('banner_fp',64,16,6,'Fp','PAUSE_LBL_FP'),('banner_bp',64,16,6,'Bp','PAUSE_LBL_BP'),
 ('banner_boots',48,16,6,'Boots','PAUSE_LBL_BOOTS'),('banner_hammer',48,16,6,'Hammer','PAUSE_LBL_HAMMER'),
 ('banner_star_energy',48,16,6,'StarEnergy','PAUSE_LBL_ENERGY'),('available',64,16,6,'Available','PAUSE_LBL_AVAILABLE'),
 ('prompt_check_abilities',128,16,7,'CheckAbilities','PAUSE_LBL_ABILITIES')]
yaml='\n# --- PAL localized labels (DE/FR/ES pause_gfx overlays) ---\n'
hdr='\n// PAL localized pause labels (DE/FR/ES)\n'
c='// Generated by tools/pal/gen_pause_langs.py: per-language pause label display lists (PAL).\n\n'
c+='''#define PAUSE_LABEL_DL(NAME, PNG, PAL, W, H, LOGW) \\
Gfx NAME[] = { \\
    gsDPPipeSync(), \\
    gsSPTexture(-1, -1, 0, G_TX_RENDERTILE, G_ON), \\
    gsDPSetCycleType(G_CYC_1CYCLE), \\
    gsDPSetTexturePersp(G_TP_NONE), \\
    gsDPSetTextureDetail(G_TD_CLAMP), \\
    gsDPSetTextureLOD(G_TL_TILE), \\
    gsDPSetTextureFilter(G_TF_POINT), \\
    gsDPSetTextureConvert(G_TC_FILT), \\
    gsDPSetTextureLUT(G_TT_RGBA16), \\
    gsDPLoadTLUT_pal16(0, PAL), \\
    gsDPLoadTextureTile_4b(PNG, G_IM_FMT_CI, W, H, 0, 0, (W) - 1, (H) - 1, 0, G_TX_NOMIRROR | G_TX_WRAP, G_TX_NOMIRROR | G_TX_WRAP, LOGW, 4, G_TX_NOLOD, G_TX_NOLOD), \\
    gsDPSetRenderMode(AA_EN | CVG_DST_FULL | ZMODE_OPA | CVG_X_ALPHA | GBL_c1(G_BL_CLR_IN, G_BL_A_IN, G_BL_CLR_MEM, G_BL_A_MEM), AA_EN | CVG_DST_FULL | ZMODE_OPA | CVG_X_ALPHA | GBL_c2(G_BL_CLR_IN, G_BL_A_IN, G_BL_CLR_MEM, G_BL_A_MEM)), \\
    gsDPSetCombineMode(G_CC_DECALRGBA, G_CC_DECALRGBA), \\
    gsSPClearGeometryMode(G_LIGHTING), \\
    gsSPSetGeometryMode(G_SHADE | G_CULL_BACK | G_SHADING_SMOOTH), \\
    gsSPEndDisplayList(), \\
}

'''
for lang,base in START.items():
    off=base
    for name,w,h,lg,suf,lbl in ITEMS:
        sz=w*h//2
        yaml+='%s_%s:\n  { type: TEXTURE, format: CI4, offset: 0x%X, width: %d, height: %d, symbol: pause_%s_%s_png }\n'%(name,lang,off,w,h,name,lang)
        yaml+='%s_%s.pal:\n  { type: TEXTURE, format: TLUT, offset: 0x%X, colors: 16, symbol: pause_%s_%s_pal }\n'%(name,lang,off+sz,name,lang)
        hdr+='static const ALIGN_ASSET(2) char pause_%s_%s_png[] = "__OTR__misc/pause/%s_%s";\n'%(name,lang,name,lang)
        hdr+='static const ALIGN_ASSET(2) char pause_%s_%s_pal[] = "__OTR__misc/pause/%s_%s.pal";\n'%(name,lang,name,lang)
        c+='static PAUSE_LABEL_DL(PauseGfx%s_%s, pause_%s_%s_png, pause_%s_%s_pal, %d, %d, %d);\n'%(suf,lang,name,lang,name,lang,w,h,lg)
        off+=sz+0x200
    c+='\n'
c+='''// [gCurrentLanguage][label]; the English entries are the base display lists of pause_gfx.c.
static Gfx* PauseGfxLabelsPal[4][9] = {
'''
for lang in ['en','de','fr','es']:
    c+='    {\n'
    for name,w,h,lg,suf,lbl in ITEMS+[('stats_bar',0,0,0,'','PAUSE_LBL_STATS')]:
        if suf=='' : ref='PauseGfxStatsBar'
        elif lang=='en': ref={'Hp':'PauseGfxBannerHp','Fp':'PauseGfxBannerFp','Bp':'PauseGfxBannerBp','Boots':'PauseGfxBannerBoots','Hammer':'PauseGfxBannerHammer','StarEnergy':'PauseGfxBannerStarEnergy','Available':'PauseGfxAvailable','CheckAbilities':'PauseGfxCheckAbilities'}[suf]
        else: ref='PauseGfx%s_%s'%(suf,lang)
        c+='        [%s] = %s,\n'%(lbl,ref)
    c+='    },\n'
c+='};\n'
open(repo+'/assets/yaml/pal/misc/pause.yml','a').write(yaml)
open(repo+'/include/assets/misc/pause.h','a').write(hdr)
open(repo+'/src/pause/pause_gfx_pal_labels.inc.c','w').write(c)
